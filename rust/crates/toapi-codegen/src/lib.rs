//! Generates the request types of a Toapi client from an OpenAPI document.
//!
//! For every route and method, e.g. `GET /users/{id}`, it emits
//!
//! - `GetUsersById`: the request, with one field per path parameter plus
//!   `query` and `body` fields when the route takes them
//! - `GetUsersByIdQuery`: the query parameters
//! - `PutUsersByIdRequestBody`: the request body
//! - `GetUsersByIdResponseBody`: the response body
//!
//! plus a type per `components/schemas` entry, and implements
//! `toapi_client::Request` for each request. The names come from
//! `toapi_core::type_name`, which the client macros use as well.
//!
//! Use it from a build script:
//!
//! ```ignore
//! // build.rs
//! fn main() {
//!     toapi_codegen::build("../server/openapi.json").unwrap();
//! }
//!
//! // src/lib.rs
//! include!(concat!(env!("OUT_DIR"), "/toapi_client.rs"));
//! ```
//!
//! Supported schemas: objects, arrays, maps (`additionalProperties`), string
//! enums, the JSON Schema primitive types with the integer and number formats
//! schemars emits, nullable types and `$ref`s to `components/schemas`.
//! Anything else becomes `serde_json::Value`.

use std::{
    collections::{BTreeMap, HashMap},
    path::Path,
};

use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use serde_json::{Map, Value, json};
use toapi_core::Segment;

#[derive(Debug)]
pub struct Error(String);

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::error::Error for Error {}

fn error(message: impl Into<String>) -> Error {
    Error(message.into())
}

/// For build scripts: generates `$OUT_DIR/toapi_client.rs` from the OpenAPI
/// document at `spec_path` and tells cargo to rerun when it changes.
pub fn build(spec_path: impl AsRef<Path>) -> Result<(), Error> {
    let spec_path = spec_path.as_ref();
    println!("cargo:rerun-if-changed={}", spec_path.display());
    let out_dir = std::env::var("OUT_DIR")
        .map_err(|_| error("OUT_DIR is not set; call this from a build script"))?;
    generate_file(spec_path, Path::new(&out_dir).join("toapi_client.rs"))
}

/// Generates Rust code from the OpenAPI document at `spec_path` into `out_path`.
pub fn generate_file(spec_path: impl AsRef<Path>, out_path: impl AsRef<Path>) -> Result<(), Error> {
    let spec_path = spec_path.as_ref();
    let spec = std::fs::read_to_string(spec_path)
        .map_err(|e| error(format!("could not read {}: {e}", spec_path.display())))?;
    let spec: Value = serde_json::from_str(&spec)
        .map_err(|e| error(format!("{} is not valid JSON: {e}", spec_path.display())))?;
    let code = generate(&spec)?;
    std::fs::write(out_path.as_ref(), code).map_err(|e| {
        error(format!(
            "could not write {}: {e}",
            out_path.as_ref().display()
        ))
    })
}

/// Generates Rust code from an OpenAPI document.
pub fn generate(spec: &Value) -> Result<String, Error> {
    let mut generator = Generator::default();

    if let Some(schemas) = spec
        .pointer("/components/schemas")
        .and_then(Value::as_object)
    {
        for (name, schema) in schemas {
            let type_name = toapi_core::pascal_case(name);
            generator.named_type(&type_name, schema, &format!("components/schemas/{name}"))?;
        }
    }

    let methods = ["get", "post", "put", "patch", "delete"];
    if let Some(paths) = spec.get("paths").and_then(Value::as_object) {
        for (path, item) in paths {
            for method in methods {
                if let Some(operation) = item.get(method) {
                    generator.operation(path, method, item, operation)?;
                }
            }
        }
    }

    let items = generator.items;
    let file: syn::File = syn::parse2(quote!(#(#items)*))
        .map_err(|e| error(format!("generated invalid code: {e}")))?;
    Ok(format!(
        "// @generated by toapi-codegen. Do not edit.\n\n{}",
        prettyplease::unparse(&file)
    ))
}

/// A Rust type for a schema.
struct Ty {
    tokens: TokenStream,
    /// Already an `Option<..>`, so optional fields don't wrap it again.
    optional: bool,
}

impl Ty {
    fn plain(tokens: TokenStream) -> Self {
        Ty {
            tokens,
            optional: false,
        }
    }
}

#[derive(Default)]
struct Generator {
    items: Vec<TokenStream>,
    /// Defined type names and where they came from, to report collisions.
    defined: HashMap<String, String>,
}

fn serde_derives() -> TokenStream {
    quote! {
        #[derive(Debug, Clone, PartialEq, ::toapi_client::__private::serde::Serialize, ::toapi_client::__private::serde::Deserialize)]
        #[serde(crate = "::toapi_client::__private::serde")]
    }
}

fn value_type() -> TokenStream {
    quote!(::toapi_client::__private::serde_json::Value)
}

fn doc(schema: &Value) -> TokenStream {
    match schema.get("description").and_then(Value::as_str) {
        Some(description) => {
            let description = format!(" {description}");
            quote!(#[doc = #description])
        }
        None => quote!(),
    }
}

fn field_ident(name: &str) -> syn::Ident {
    let field = toapi_core::field_name(name);
    if toapi_core::is_keyword(&field) {
        syn::Ident::new_raw(&field, proc_macro2::Span::call_site())
    } else {
        format_ident!("{}", field)
    }
}

fn is_string_enum(schema: &Value) -> bool {
    schema
        .get("enum")
        .and_then(Value::as_array)
        .is_some_and(|values| !values.is_empty() && values.iter().all(Value::is_string))
}

fn has_properties(schema: &Value) -> bool {
    schema
        .get("properties")
        .and_then(Value::as_object)
        .is_some_and(|p| !p.is_empty())
}

impl Generator {
    fn define(&mut self, name: &str, origin: &str, item: TokenStream) -> Result<(), Error> {
        if let Some(previous) = self.defined.insert(name.to_string(), origin.to_string()) {
            return Err(error(format!(
                "`{previous}` and `{origin}` both map to the type name `{name}`"
            )));
        }
        self.items.push(item);
        Ok(())
    }

    /// Defines `name` for `schema`: a struct or enum when the schema is one,
    /// otherwise a type alias.
    fn named_type(&mut self, name: &str, schema: &Value, origin: &str) -> Result<(), Error> {
        if has_properties(schema) {
            self.object(name, schema, origin)
        } else if is_string_enum(schema) {
            self.string_enum(name, schema, origin)
        } else {
            let ty = self.ty(schema, name, origin)?.tokens;
            let ident = format_ident!("{}", name);
            let doc = doc(schema);
            self.define(name, origin, quote!(#doc pub type #ident = #ty;))
        }
    }

    fn object(&mut self, name: &str, schema: &Value, origin: &str) -> Result<(), Error> {
        let required: Vec<&str> = schema
            .get("required")
            .and_then(Value::as_array)
            .map(|r| r.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        let mut fields = Vec::new();
        if let Some(properties) = schema.get("properties").and_then(Value::as_object) {
            for (property, property_schema) in properties {
                let hint = format!("{name}{}", toapi_core::pascal_case(property));
                let ty = self.ty(property_schema, &hint, &format!("{origin}.{property}"))?;
                let ident = field_ident(property);
                let rename = (ident.to_string().trim_start_matches("r#") != property)
                    .then(|| quote!(#[serde(rename = #property)]));
                let optional = !required.contains(&property.as_str()) || ty.optional;
                let tokens = ty.tokens;
                let (ty, attrs) = match (optional, ty.optional) {
                    (false, _) => (tokens, quote!()),
                    (true, true) => (
                        tokens,
                        quote!(#[serde(default, skip_serializing_if = "Option::is_none")]),
                    ),
                    (true, false) => (
                        quote!(Option<#tokens>),
                        quote!(#[serde(default, skip_serializing_if = "Option::is_none")]),
                    ),
                };
                let doc = doc(property_schema);
                fields.push(quote!(#doc #rename #attrs pub #ident: #ty));
            }
        }
        let ident = format_ident!("{}", name);
        let derives = serde_derives();
        let doc = doc(schema);
        self.define(
            name,
            origin,
            quote! {
                #doc
                #derives
                pub struct #ident { #(#fields,)* }
            },
        )
    }

    fn string_enum(&mut self, name: &str, schema: &Value, origin: &str) -> Result<(), Error> {
        let variants = schema["enum"].as_array().unwrap().iter().map(|value| {
            let value = value.as_str().unwrap();
            let mut variant = toapi_core::pascal_case(value);
            if variant.is_empty() || variant.starts_with(|c: char| c.is_ascii_digit()) {
                variant = format!("V{variant}");
            }
            let variant = format_ident!("{}", variant);
            quote!(#[serde(rename = #value)] #variant)
        });
        let ident = format_ident!("{}", name);
        let derives = serde_derives();
        let doc = doc(schema);
        self.define(
            name,
            origin,
            quote! {
                #doc
                #derives
                pub enum #ident { #(#variants,)* }
            },
        )
    }

    /// The type of a schema used inside another type. Inline objects and
    /// enums are defined under `hint`.
    fn ty(&mut self, schema: &Value, hint: &str, origin: &str) -> Result<Ty, Error> {
        let Some(object) = schema.as_object() else {
            return Ok(Ty::plain(value_type()));
        };

        if let Some(reference) = object.get("$ref").and_then(Value::as_str) {
            let name = reference
                .strip_prefix("#/components/schemas/")
                .ok_or_else(|| error(format!("{origin}: unsupported $ref `{reference}`")))?;
            let ident = format_ident!("{}", toapi_core::pascal_case(name));
            return Ok(Ty::plain(quote!(#ident)));
        }

        // `anyOf: [X, {type: null}]`, as schemars emits for Option<Struct>
        for key in ["anyOf", "oneOf"] {
            if let Some(variants) = object.get(key).and_then(Value::as_array) {
                let (nulls, others): (Vec<&Value>, Vec<&Value>) = variants
                    .iter()
                    .partition(|v| v.get("type").and_then(Value::as_str) == Some("null"));
                if nulls.len() == 1 && others.len() == 1 {
                    let inner = self.ty(others[0], hint, origin)?;
                    return Ok(optional(inner));
                }
                return Ok(Ty::plain(value_type()));
            }
        }

        // `type: [X, "null"]`, as schemars emits for Option<primitive>
        if let Some(types) = object.get("type").and_then(Value::as_array) {
            let others: Vec<&Value> = types
                .iter()
                .filter(|t| t.as_str() != Some("null"))
                .collect();
            if others.len() == 1 {
                let mut non_null: Map<String, Value> = object.clone();
                non_null.insert("type".into(), others[0].clone());
                let inner = self.ty(&Value::Object(non_null), hint, origin)?;
                return Ok(if others.len() < types.len() {
                    optional(inner)
                } else {
                    inner
                });
            }
            return Ok(Ty::plain(value_type()));
        }

        if is_string_enum(schema) {
            self.string_enum(hint, schema, origin)?;
            let ident = format_ident!("{}", hint);
            return Ok(Ty::plain(quote!(#ident)));
        }

        let format = object.get("format").and_then(Value::as_str);
        let tokens = match object.get("type").and_then(Value::as_str) {
            Some("string") => quote!(String),
            Some("boolean") => quote!(bool),
            Some("null") => quote!(()),
            Some("integer") => match format {
                Some("int8") => quote!(i8),
                Some("int16") => quote!(i16),
                Some("int32") => quote!(i32),
                Some("uint8") => quote!(u8),
                Some("uint16") => quote!(u16),
                Some("uint32") => quote!(u32),
                Some("uint64") => quote!(u64),
                Some("uint") => quote!(usize),
                Some("int") => quote!(isize),
                _ => quote!(i64),
            },
            Some("number") => match format {
                Some("float") => quote!(f32),
                _ => quote!(f64),
            },
            Some("array") => {
                let items = match object.get("items") {
                    Some(items) => self.ty(items, &format!("{hint}Item"), origin)?.tokens,
                    None => value_type(),
                };
                quote!(Vec<#items>)
            }
            Some("object") | None if has_properties(schema) => {
                self.object(hint, schema, origin)?;
                let ident = format_ident!("{}", hint);
                quote!(#ident)
            }
            Some("object") => match object.get("additionalProperties") {
                Some(values) if values.is_object() => {
                    let values = self.ty(values, &format!("{hint}Value"), origin)?.tokens;
                    quote!(::std::collections::HashMap<String, #values>)
                }
                _ => value_type(),
            },
            _ => value_type(),
        };
        Ok(Ty::plain(tokens))
    }

    fn operation(
        &mut self,
        path: &str,
        method: &str,
        item: &Value,
        operation: &Value,
    ) -> Result<(), Error> {
        let origin = format!("{} {path}", method.to_uppercase());
        let name =
            toapi_core::type_name(method, path).map_err(|e| error(format!("{origin}: {e}")))?;
        let segments = toapi_core::parse_path(path).map_err(|e| error(format!("{origin}: {e}")))?;

        // path-item level parameters apply to every operation, operation level ones win
        let mut path_params: BTreeMap<String, Value> = BTreeMap::new();
        let mut query_params: Vec<(String, Value, bool)> = Vec::new();
        for parameter in [item.get("parameters"), operation.get("parameters")]
            .into_iter()
            .flatten()
            .filter_map(Value::as_array)
            .flatten()
        {
            let param_name = parameter
                .get("name")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let schema = parameter
                .get("schema")
                .cloned()
                .unwrap_or(json!({ "type": "string" }));
            match parameter.get("in").and_then(Value::as_str) {
                Some("path") => {
                    path_params.insert(param_name.to_string(), schema);
                }
                Some("query") => {
                    let required = parameter
                        .get("required")
                        .and_then(Value::as_bool)
                        .unwrap_or(false);
                    query_params.retain(|(n, _, _)| n != param_name);
                    query_params.push((param_name.to_string(), schema, required));
                }
                _ => {}
            }
        }

        let mut fields = Vec::new();
        let mut format_string = String::new();
        let mut format_args = Vec::new();
        for segment in &segments {
            format_string.push('/');
            match segment {
                Segment::Static(s) => {
                    format_string.push_str(&s.replace('{', "{{").replace('}', "}}"))
                }
                Segment::Param { name: param, .. } => {
                    let schema = path_params
                        .get(param)
                        .cloned()
                        .unwrap_or(json!({ "type": "string" }));
                    let hint = format!("{name}{}", toapi_core::pascal_case(param));
                    let ty = self
                        .ty(&schema, &hint, &format!("{origin} {{{param}}}"))?
                        .tokens;
                    let ident = field_ident(param);
                    fields.push(quote!(pub #ident: #ty));
                    format_string.push_str("{}");
                    format_args
                        .push(quote!(::toapi_client::__private::encode_path_segment(&self.#ident)));
                }
            }
        }
        if segments.is_empty() {
            format_string.push('/');
        }

        let mut methods = Vec::new();
        if !query_params.is_empty() {
            let query_name = toapi_core::query_type_name(&name);
            let schema = json!({
                "type": "object",
                "properties": query_params
                    .iter()
                    .map(|(n, s, _)| (n.clone(), s.clone()))
                    .collect::<Map<String, Value>>(),
                "required": query_params
                    .iter()
                    .filter(|(_, _, required)| *required)
                    .map(|(n, _, _)| n.clone())
                    .collect::<Vec<_>>(),
            });
            self.object(&query_name, &schema, &format!("{origin} query"))?;
            let ident = format_ident!("{}", query_name);
            fields.push(quote!(pub query: #ident));
            methods.push(quote! {
                fn query(&self) -> Result<Option<String>, ::toapi_client::Error> {
                    ::toapi_client::__private::query_string(&self.query)
                }
            });
        }

        if let Some(schema) = operation.pointer("/requestBody/content/application~1json/schema") {
            let body_name = toapi_core::request_body_type_name(&name);
            self.named_type(&body_name, schema, &format!("{origin} request body"))?;
            let ident = format_ident!("{}", body_name);
            fields.push(quote!(pub body: #ident));
            methods.push(quote! {
                fn body(&self) -> Result<Option<Vec<u8>>, ::toapi_client::Error> {
                    ::toapi_client::__private::json_body(&self.body)
                }
            });
        }

        let response_name = toapi_core::response_body_type_name(&name);
        let response_origin = format!("{origin} response body");
        match success_schema(operation) {
            Some(schema) => self.named_type(&response_name, schema, &response_origin)?,
            None => {
                let ident = format_ident!("{}", response_name);
                self.define(
                    &response_name,
                    &response_origin,
                    quote!(pub type #ident = ();),
                )?;
            }
        }

        let path_body = if format_args.is_empty() {
            quote!(String::from(#format_string))
        } else {
            quote!(format!(#format_string, #(#format_args),*))
        };
        let ident = format_ident!("{}", name);
        let response_ident = format_ident!("{}", response_name);
        let method_ident = format_ident!("{}", method.to_uppercase());
        let kind = if toapi_core::is_query_method(method) {
            quote!(QueryRequest)
        } else {
            quote!(MutationRequest)
        };
        let doc = format!(" `{} {path}`", method.to_uppercase());
        self.define(
            &name,
            &origin,
            quote! {
                #[doc = #doc]
                #[derive(Debug, Clone, PartialEq)]
                pub struct #ident { #(#fields,)* }

                impl ::toapi_client::Request for #ident {
                    type Response = #response_ident;
                    const METHOD: ::toapi_client::Method = ::toapi_client::Method::#method_ident;
                    const TEMPLATE: &'static str = #path;

                    fn path(&self) -> String {
                        #path_body
                    }

                    #(#methods)*
                }

                impl ::toapi_client::#kind for #ident {}
            },
        )
    }
}

fn optional(inner: Ty) -> Ty {
    if inner.optional {
        return inner;
    }
    let tokens = inner.tokens;
    Ty {
        tokens: quote!(Option<#tokens>),
        optional: true,
    }
}

/// The JSON schema of the first 2xx response.
fn success_schema(operation: &Value) -> Option<&Value> {
    let responses = operation.get("responses")?.as_object()?;
    let mut codes: Vec<&String> = responses
        .keys()
        .filter(|code| code.starts_with('2'))
        .collect();
    codes.sort();
    codes
        .into_iter()
        .find_map(|code| responses[code].pointer("/content/application~1json/schema"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generates_request_types() {
        let spec = json!({
            "openapi": "3.1.0",
            "paths": {
                "/users/{id}": {
                    "get": {
                        "parameters": [
                            { "name": "id", "in": "path", "required": true, "schema": { "type": "integer", "format": "uint64" } },
                            { "name": "includePosts", "in": "query", "required": false, "schema": { "type": ["boolean", "null"] } }
                        ],
                        "responses": { "200": { "content": { "application/json": { "schema": { "$ref": "#/components/schemas/User" } } } } }
                    },
                    "put": {
                        "parameters": [{ "name": "id", "in": "path", "required": true, "schema": { "type": "integer", "format": "uint64" } }],
                        "requestBody": { "content": { "application/json": { "schema": {
                            "type": "object",
                            "properties": { "name": { "type": "string" }, "role": { "enum": ["admin", "member"], "type": "string" } },
                            "required": ["name", "role"]
                        } } } },
                        "responses": { "200": { "description": "OK" } }
                    }
                }
            },
            "components": { "schemas": { "User": {
                "type": "object",
                "properties": { "id": { "type": "integer", "format": "uint64" }, "name": { "type": "string" } },
                "required": ["id", "name"]
            } } }
        });
        let code = generate(&spec).unwrap();
        for expected in [
            "pub struct User {",
            "pub struct GetUsersById {",
            "pub id: u64,",
            "pub query: GetUsersByIdQuery,",
            "pub struct GetUsersByIdQuery {",
            "pub include_posts: Option<bool>,",
            "pub type GetUsersByIdResponseBody = User;",
            "pub struct PutUsersByIdRequestBody {",
            "pub role: PutUsersByIdRequestBodyRole,",
            "pub enum PutUsersByIdRequestBodyRole {",
            "pub type PutUsersByIdResponseBody = ();",
            "impl ::toapi_client::QueryRequest for GetUsersById {}",
            "impl ::toapi_client::MutationRequest for PutUsersById {}",
        ] {
            assert!(code.contains(expected), "missing `{expected}` in\n{code}");
        }
    }

    #[test]
    fn reports_name_collisions() {
        let spec = json!({
            "paths": {
                "/user-groups": { "get": { "responses": {} } },
                "/user/groups": { "get": { "responses": {} } }
            }
        });
        let err = generate(&spec).unwrap_err().to_string();
        assert!(err.contains("GetUserGroups"), "{err}");
    }
}
